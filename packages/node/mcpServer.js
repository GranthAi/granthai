// MCP server (Streamable HTTP transport, stateless) built from the generated OpenAPI spec.
// Every operation observed in the spec is exposed as an MCP tool; calling a tool
// performs the real HTTP request against the API and returns the response.
const { version } = require("./package.json");

const SUPPORTED_PROTOCOL_VERSIONS = ["2025-11-25", "2025-06-18", "2025-03-26"];
const HTTP_METHODS = ["get", "post", "put", "patch", "delete"];
const TOOL_CALL_TIMEOUT_MS = 30000;

function toolNameFor(method, path) {
	const slug = path
		.replace(/[{}]/g, "")
		.split("/")
		.filter(Boolean)
		.join("_")
		.replace(/[^a-zA-Z0-9_-]/g, "_");
	return `${method}_${slug || "root"}`.slice(0, 64);
}

function buildTools(spec) {
	const tools = [];
	const used = new Set();

	for (const path in spec.paths) {
		for (const method of HTTP_METHODS) {
			const operation = spec.paths[path][method];
			if (!operation) continue;

			let name = toolNameFor(method, path);
			for (let i = 2; used.has(name); i++) {
				name = `${toolNameFor(method, path).slice(0, 60)}_${i}`;
			}
			used.add(name);

			const properties = {};
			const required = [];
			for (const param of operation.parameters || []) {
				if (param.in !== "path" && param.in !== "query") continue;
				properties[param.name] = { ...param.schema, description: `${param.in} parameter` };
				if (param.required) required.push(param.name);
			}

			let bodyContentType;
			const content = operation.requestBody && operation.requestBody.content;
			if (content && Object.keys(content).length > 0) {
				bodyContentType = Object.keys(content).find((type) => type.includes("json")) || Object.keys(content)[0];
				properties.body = { ...content[bodyContentType].schema, description: "Request body" };
			}

			tools.push({
				name,
				description: operation.summary || `${method.toUpperCase()} ${path}`,
				inputSchema: { type: "object", properties, ...(required.length ? { required } : {}) },
				_operation: { method, path, parameters: operation.parameters || [], bodyContentType }
			});
		}
	}
	return tools;
}

async function callTool(tool, args, { origin, authorization }) {
	const { method, path, parameters, bodyContentType } = tool._operation;
	let urlPath = path;
	const query = new URLSearchParams();

	for (const param of parameters) {
		const value = args[param.name];
		if (value === undefined || value === null) continue;
		if (param.in === "path") urlPath = urlPath.replace(`{${param.name}}`, encodeURIComponent(String(value)));
		if (param.in === "query") query.append(param.name, String(value));
	}

	const missing = urlPath.match(/{[^}]+}/g);
	if (missing) {
		return { content: [{ type: "text", text: `Missing required path parameter(s): ${missing.join(", ")}` }], isError: true };
	}

	const url = new URL(urlPath, origin);
	url.search = query.toString();

	const headers = { accept: "application/json, text/plain, */*" };
	if (authorization) headers.authorization = authorization;
	let body;
	if (args.body !== undefined && method !== "get" && method !== "delete") {
		const contentType = bodyContentType && bodyContentType.includes("json") ? bodyContentType : "application/json";
		headers["content-type"] = contentType;
		body = JSON.stringify(args.body);
	}

	try {
		const response = await fetch(url, { method: method.toUpperCase(), headers, body, signal: AbortSignal.timeout(TOOL_CALL_TIMEOUT_MS) });
		const text = await response.text();
		return {
			content: [{ type: "text", text: `HTTP ${response.status} ${response.statusText}\n\n${text}` }],
			isError: !response.ok
		};
	} catch (err) {
		return { content: [{ type: "text", text: `Request to ${method.toUpperCase()} ${url.pathname} failed: ${err.message}` }], isError: true };
	}
}

function rpcResult(id, result) {
	return { jsonrpc: "2.0", id, result };
}

function rpcError(id, code, message) {
	return { jsonrpc: "2.0", id, error: { code, message } };
}

async function handleMessage(message, ctx) {
	if (!message || message.jsonrpc !== "2.0") return rpcError(message?.id ?? null, -32600, "Invalid Request");
	// Client responses and notifications get no reply
	if (message.method === undefined || message.id === undefined) return null;

	const { id, method, params = {} } = message;
	switch (method) {
		case "initialize": {
			const requested = params.protocolVersion;
			const protocolVersion = SUPPORTED_PROTOCOL_VERSIONS.includes(requested) ? requested : SUPPORTED_PROTOCOL_VERSIONS[0];
			return rpcResult(id, {
				protocolVersion,
				capabilities: { tools: { listChanged: false } },
				serverInfo: { name: ctx.spec.info.title, version },
				instructions:
					"Tools are generated by GranthAi from API traffic observed by this server. Each tool calls one API endpoint and returns the raw HTTP response. Endpoints appear here after they have handled at least one request."
			});
		}
		case "ping":
			return rpcResult(id, {});
		case "tools/list":
			return rpcResult(id, { tools: buildTools(ctx.spec).map(({ _operation, ...tool }) => tool) });
		case "tools/call": {
			const tool = buildTools(ctx.spec).find((t) => t.name === params.name);
			if (!tool) return rpcError(id, -32602, `Unknown tool: ${params.name}`);
			return rpcResult(id, await callTool(tool, params.arguments || {}, ctx));
		}
		default:
			return rpcError(id, -32601, `Method not found: ${method}`);
	}
}

function readBody(req) {
	if (req.body !== undefined && !(Buffer.isBuffer(req.body) && req.body.length === 0)) {
		if (Buffer.isBuffer(req.body) || typeof req.body === "string") return Promise.resolve(JSON.parse(req.body.toString()));
		if (typeof req.body === "object" && Object.keys(req.body).length > 0) return Promise.resolve(req.body);
	}
	return new Promise((resolve, reject) => {
		let data = "";
		req.setEncoding("utf8");
		req.on("data", (chunk) => (data += chunk));
		req.on("end", () => {
			try {
				resolve(JSON.parse(data));
			} catch (err) {
				reject(err);
			}
		});
		req.on("error", reject);
	});
}

function isOriginAllowed(req, allowedOrigins) {
	const origin = req.get("origin");
	if (!origin) return true;
	if (allowedOrigins.includes(origin)) return true;
	try {
		return new URL(origin).host === req.get("host");
	} catch (err) {
		return false;
	}
}

async function handleMcpRequest(req, res, { spec, baseUrl, allowedOrigins = [] }) {
	// Protects against DNS rebinding as required by the Streamable HTTP transport spec
	if (!isOriginAllowed(req, allowedOrigins)) {
		return res.status(403).json(rpcError(null, -32000, "Origin not allowed"));
	}

	if (req.method !== "POST") {
		// Stateless server: no standalone SSE stream (GET) and no sessions to terminate (DELETE)
		res.set("Allow", "POST");
		return res.status(405).json(rpcError(null, -32000, "Method not allowed"));
	}

	let payload;
	try {
		payload = await readBody(req);
	} catch (err) {
		return res.status(400).json(rpcError(null, -32700, "Parse error"));
	}

	let origin;
	try {
		origin = new URL(baseUrl).origin;
	} catch (err) {
		origin = `${req.protocol}://${req.get("host")}`;
	}
	const ctx = { spec, origin, authorization: req.get("authorization") };

	const messages = Array.isArray(payload) ? payload : [payload];
	const responses = (await Promise.all(messages.map((message) => handleMessage(message, ctx)))).filter(Boolean);

	if (responses.length === 0) return res.status(202).end();
	return res.status(200).json(Array.isArray(payload) ? responses : responses[0]);
}

module.exports = handleMcpRequest;
